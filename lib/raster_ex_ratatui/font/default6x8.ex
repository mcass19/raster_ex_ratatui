  @hand_drawn Map.new(@glyph_data, fn {codepoint, art} ->
                pad =
                  case art |> String.split("\n", trim: true) |> hd() |> String.length() do
                    5 -> {1, 1}
                    _ -> {0, 0}
                  end

                {codepoint, Art.parse(art, @size, pad: pad)}
              end)

  @glyphs [Generated.braille(@size), Generated.eighths(@size), Generated.quadrants(@size)]
          |> Enum.reduce(&Map.merge(&2, &1))
          |> Map.merge(@hand_drawn)

  @missing Generated.hatched(@size)

  @impl true
  @doc """
  Cell size in pixels: `{6, 8}`.

  ## Examples

      iex> RasterExRatatui.Font.Default6x8.cell_size()
      {6, 8}
  """
  @spec cell_size() :: {6, 8}
  def cell_size, do: @size

  @impl true
  @doc """
  The 48-bit bitmap for `codepoint`, or the hatched placeholder.

  ## Examples

      iex> RasterExRatatui.Font.Default6x8.glyph(?\\s)
      <<0::48>>

      iex> RasterExRatatui.Font.Default6x8.glyph(0x1F600) == RasterExRatatui.Font.Generated.hatched({6, 8})
      true
  """
  @spec glyph(non_neg_integer()) :: <<_::48>>
  def glyph(codepoint) when is_integer(codepoint), do: Map.get(@glyphs, codepoint, @missing)

  @impl true
  @doc """
  Whether `codepoint` has a hand-drawn or generated glyph.

  ## Examples

      iex> RasterExRatatui.Font.Default6x8.has_glyph?(0x2588)
      true

      iex> RasterExRatatui.Font.Default6x8.has_glyph?(0x1F600)
      false
  """
  @spec has_glyph?(non_neg_integer()) :: boolean()
  def has_glyph?(codepoint) when is_integer(codepoint), do: Map.has_key?(@glyphs, codepoint)

  @doc """
  Every codepoint with a glyph, sorted ascending. For tests and tooling.

  ## Examples

      iex> ?A in RasterExRatatui.Font.Default6x8.codepoints()
      true
  """
  @spec codepoints() :: [non_neg_integer()]
  def codepoints, do: @glyphs |> Map.keys() |> Enum.sort()
