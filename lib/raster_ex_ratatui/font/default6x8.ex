  @moduledoc """
  The built-in 6×8 monospace bitmap font, drawn for a 400×300 1-bit e-ink panel and readable on any panel with an integer `scale:`.

  Each cell is 6×8 pixels: text glyphs are drawn 5×7 with one blank column on the right (inter-cell spacing) and one blank row at the bottom (inter-line spacing); box-drawing and block glyphs fill all 48 pixels so they join across cells.

  ## Coverage

  Hand-drawn:

    * All of printable ASCII (`U+0020`–`U+007E`)
    * Light box drawing `─ │ ┌ ┐ └ ┘ ├ ┤ ┬ ┴ ┼`, and the corners and lines of every `Block` border type: rounded `╭ ╮ ╰ ╯`, heavy `━ ┃ ┏ ┓ ┗ ┛`, double `═ ║ ╔ ╗ ╚ ╝`
    * Block elements: `█ ▀ ▄ ░ ▒ ▓`
    * Symbols: `° · • … ← ↑ → ↓ ✓ ✗ ▲ ▶ ▼ ◀ ○ ●`

  Generated from their Unicode geometry by `RasterExRatatui.Font.Generated`:

    * The braille block `U+2800`–`U+28FF` (the `Canvas` widget's default marker); each dot is a solid 3×2 block, so neighbouring dots merge into lines
    * Eighth blocks `▁ ▂ ▃ ▅ ▆ ▇`, `▏ ▎ ▍ ▌ ▋ ▊ ▉`, `▐ ▔ ▕`
    * Quadrants `▖ ▗ ▘ ▙ ▚ ▛ ▜ ▝ ▞ ▟` (`BigText`'s `:quadrant` size)

  Hand-drawn glyphs win where both exist. Any other codepoint renders as a hatched box (`RasterExRatatui.Font.Generated.hatched/1`), so it is obvious in a rendering rather than silently blank.

  ## Examples

      iex> alias RasterExRatatui.Font.{Art, Default6x8}
      iex> Default6x8.glyph(?A) |> Art.render(Default6x8.cell_size())
      ".###..\\n#...#.\\n#...#.\\n#####.\\n#...#.\\n#...#.\\n#...#.\\n......\\n"
  """

